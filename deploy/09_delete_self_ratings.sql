-- =============================================================================
--  سازمت | حذف امتیازهایی که صاحب آگهی به آگهی خودش داده
-- =============================================================================
--
--  چرا این فایل لازم شد
--  --------------------
--  قرار بود کسی نتواند به آگهی خودش امتیاز بدهد. محافظِ این کار در
--  کد بود، ولی روی این سرور بی‌صدا از کار افتاده بود. دلیلش نوع
--  داده بود، نه منطق:
--
--      $ad->user_id === auth()->id()
--
--  سمت راست همیشه عدد است، ولی درایور دیتابیسِ این هاست ستون‌ها را
--  رشته برمی‌گرداند. و '3' === 3 در PHP نتیجه‌اش false است. پس شرط
--  هیچ‌وقت برقرار نمی‌شد و فرم امتیازدهی به صاحب آگهی هم نشان داده
--  می‌شد.
--
--  نسخه‌ی جدیدِ کد این را از ریشه بسته است (کلیدهای خارجی در مدل‌ها
--  صراحتاً به عدد صحیح تبدیل می‌شوند). ولی امتیازهایی که در این
--  فاصله ثبت شده‌اند هنوز در دیتابیس‌اند و در میانگینِ آگهی حساب
--  می‌شوند. این فایل همان‌ها را پاک می‌کند.
--
--  چه چیزی حذف می‌شود
--  ------------------
--  فقط ردیف‌هایی از `ad_ratings` که امتیازدهنده، خودِ صاحبِ همان
--  آگهی باشد. امتیازهای کاربران واقعی دست نمی‌خورند.
--
--  در phpMyAdmin روی دیتابیس sazmat_sa ایمپورت کنید.
--  اجرای دوباره‌ی این فایل بی‌خطر است - بار دوم چیزی برای حذف
--  نمی‌ماند و خطا هم نمی‌دهد.
--
--  ⚠️ این فایل را بعد از آپلودِ کد جدید اجرا کنید، نه قبلش. وگرنه
--     صاحب آگهی می‌تواند دوباره امتیاز بدهد.
-- =============================================================================

SET NAMES utf8mb4;

-- ---------------------------------------------------------------------------
-- ۱) چه چیزی قرار است پاک شود
-- ---------------------------------------------------------------------------
--
--  توجه: ایمپورت، همه‌ی دستورهای این فایل را پشت سر هم اجرا می‌کند؛
--  یعنی این SELECT جلوی حذف را نمی‌گیرد، فقط در خروجی نشانتان می‌دهد
--  چه ردیف‌هایی پاک شدند.
--
--  اگر می‌خواهید اول فقط نگاه کنید و بعد تصمیم بگیرید، به‌جای
--  ایمپورتِ فایل، همین یک دستور را در تبِ SQL کپی و اجرا کنید. خروجی
--  خالی یعنی چنین امتیازی وجود ندارد و اصلاً لازم نیست این فایل را
--  اجرا کنید.

SELECT
    r.id              AS rating_id,
    r.ad_id,
    a.title           AS ad_title,
    a.slug            AS ad_slug,
    r.user_id         AS rater_id,
    u.name            AS rater_name,
    r.rating,
    r.comment,
    r.comment_status
FROM ad_ratings r
JOIN ads   a ON a.id = r.ad_id
LEFT JOIN users u ON u.id = r.user_id
WHERE r.user_id = a.user_id;

-- ---------------------------------------------------------------------------
-- ۲) حذف
-- ---------------------------------------------------------------------------
--
--  MySQL اجازه نمی‌دهد در یک DELETE به همان جدولی که دارد از آن
--  حذف می‌کند در زیرکوئری نگاه کند. برای همین از JOIN استفاده شده
--  که هم مجاز است و هم سریع‌تر.

DELETE r
FROM ad_ratings r
JOIN ads a ON a.id = r.ad_id
WHERE r.user_id = a.user_id;

-- ---------------------------------------------------------------------------
-- ۳) بعد از حذف: باید صفر ردیف برگردد
-- ---------------------------------------------------------------------------

SELECT COUNT(*) AS self_ratings_remaining
FROM ad_ratings r
JOIN ads a ON a.id = r.ad_id
WHERE r.user_id = a.user_id;

-- ---------------------------------------------------------------------------
-- ۴) میانگین آگهی‌ها بعد از پاک‌سازی
-- ---------------------------------------------------------------------------
--
--  میانگین و تعداد امتیاز در زمان نمایش صفحه محاسبه می‌شوند، نه در
--  ستونی جداگانه. پس هیچ چیزی لازم نیست به‌روز شود - همین که ردیف
--  حذف شد، میانگین خودبه‌خود درست می‌شود. این کوئری فقط برای اطمینان
--  خاطر است.

SELECT
    a.id,
    a.title,
    COUNT(r.id)                 AS rating_count,
    ROUND(AVG(r.rating), 2)     AS rating_average
FROM ads a
LEFT JOIN ad_ratings r ON r.ad_id = a.id
GROUP BY a.id, a.title
ORDER BY a.id;
