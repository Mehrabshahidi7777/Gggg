-- =============================================================================
--  سازمت | حذف دو آگهی آزمایشی
-- =============================================================================
--
--  این دو آگهی محتوای تستی هستند و اسلاگشان هم از ترانویسیِ قدیمی
--  مانده (بی‌معنی برای کاربر و گوگل):
--
--      id 33 | محصول | «داب»  | slug: dab
--      id 34 | خدمت  | «قتقت» | slug: ktkt
--
--  بررسی شد که هیچ رکورد دیگری به آنها وابسته نیست: نه سفارشی، نه
--  نظری، نه امتیازی. تنها چیزی که با آنها حذف می‌شود، دو ردیف در
--  جدول `ad_images` است که خودِ دیتابیس با ON DELETE CASCADE پاک
--  می‌کند.
--
--  حذف بر اساس «اسلاگ» انجام می‌شود، نه شناسه. اگر این آگهی‌ها را
--  از قبل دستی حذف کرده باشید، این فایل هیچ کاری نمی‌کند و خطا هم
--  نمی‌دهد. اسلاگ‌های تازه فارسی‌اند، پس هیچ آگهی جدیدی تصادفاً با
--  این شرط مطابقت نمی‌کند.
--
--  در phpMyAdmin روی دیتابیس sazmat_sa ایمپورت کنید.
--  اجرای دوباره‌ی این فایل بی‌خطر است.
-- =============================================================================

SET NAMES utf8mb4;

-- ---------------------------------------------------------------------------
-- ۱) پیش از حذف: ببینید دقیقاً چه چیزی قرار است پاک شود
-- ---------------------------------------------------------------------------
--
-- خروجی این دستور در phpMyAdmin نمایش داده می‌شود. اگر ردیفی جز
-- همان دو آگهی آزمایشی دیدید، ادامه ندهید و به من بگویید.
--
SELECT
    a.`id`,
    a.`type`,
    a.`title`,
    a.`slug`,
    (SELECT COUNT(*) FROM `ad_images` i WHERE i.`ad_id` = a.`id`) AS `images_to_delete`
FROM `ads` a
WHERE a.`slug` IN ('dab', 'ktkt');


-- ---------------------------------------------------------------------------
-- ۲) حذف
-- ---------------------------------------------------------------------------
--
-- ردیف‌های `ad_images` به‌خاطر ON DELETE CASCADE خودکار پاک می‌شوند.
--
DELETE FROM `ads` WHERE `slug` IN ('dab', 'ktkt');


-- =============================================================================
--  فایل‌های تصویر روی دیسک
-- =============================================================================
--
--  SQL فقط ردیف دیتابیس را پاک می‌کند، نه فایل را. این دو فایل روی
--  دیسک باقی می‌مانند:
--
--      public_html/storage/ads/6aaec1d2efc2b6.42903696.jpg
--      public_html/storage/ads/6aaec2de5f1083.73742045.jpg
--
--  کاری لازم نیست: دستور پاک‌سازی شبانه (sazmat:cleanup) که هر شب
--  ساعت ۳ از همان کرون‌جاب فعلی اجرا می‌شود، فایل‌های بدون مرجع در
--  دیتابیس را که بیش از ۲۴ ساعت از ساختشان گذشته باشد خودش حذف
--  می‌کند.
--
--  اگر عجله دارید، می‌توانید همین حالا از File Manager هاست دستی
--  پاکشان کنید.
-- =============================================================================
