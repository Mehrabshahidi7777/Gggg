-- =============================================================================
--  سازمت | وزن امتیاز بر اساس سن حساب
-- =============================================================================
--
--  مسئله چه بود
--  ------------
--  ساختن حساب تازه در سایت رایگان و آنی است. بدون هیچ محافظی، کسی که
--  بخواهد رقیبش را خراب کند یا آگهی خودش را بالا ببرد فقط باید چند
--  حساب بسازد و ستاره بدهد - و میانگین همان‌قدر جابه‌جا می‌شود که با
--  رأی چند مشتری واقعی.
--
--  این فایل چه می‌کند
--  ------------------
--  یک ستون `weight` به جدول `ad_ratings` اضافه می‌کند. از این به بعد
--  هر امتیاز، بسته به اینکه حسابِ امتیازدهنده در لحظه‌ی رأی چند روزه
--  بوده، وزن می‌گیرد:
--
--      کمتر از ۳ روز   →  ۰.۲۵
--      ۳ تا ۱۴ روز     →  ۰.۵۰
--      ۱۴ تا ۶۰ روز    →  ۰.۷۵
--      ۶۰ روز به بالا  →  ۱.۰۰
--
--  و میانگین آگهی به‌جای میانگین ساده، میانگین وزنی می‌شود.
--
--  یک مثال واقعی: آگهی‌ای که یک مشتری قدیمی ۵ ستاره داده و چهار حساب
--  تازه‌ساخته ۱ ستاره، با حساب ساده میانگینش ۱.۸ می‌شد. با وزن‌دهی
--  می‌شود ۳.۰.
--
--  ⚠️ این تقلب را گران‌تر می‌کند، نه غیرممکن
--  ------------------------------------------
--  کسی که حاضر باشد حساب‌هایش را دو ماه نگه دارد، همچنان وزن کامل
--  می‌گیرد. این یک سد نیست، یک هزینه است.
--
--  اعداد بالا در فایل زیر قابل تنظیم‌اند و تغییرشان نیاز به تغییر کد
--  یا ایمپورت دوباره ندارد:
--
--      zzz/config/marketplace.php  →  کلید 'rating_weights'
--
--  ⚠️ ترتیب کار
--  ------------
--  این فایل را *قبل از* آپلود کد جدید ایمپورت کنید. کد جدید انتظار
--  دارد ستون `weight` وجود داشته باشد و بدون آن صفحه‌های آگهی خطا
--  می‌دهند.
--
--  امتیازهای موجود همگی وزن ۱.۰۰ می‌گیرند - آنها زیر قانون دیگری ثبت
--  شده‌اند و عقب‌گرد جریمه نمی‌شوند.
--
--  در phpMyAdmin روی دیتابیس sazmat_sa ایمپورت کنید.
--  اجرای دوباره‌ی این فایل بی‌خطر است.
-- =============================================================================

SET NAMES utf8mb4;

-- ---------------------------------------------------------------------------
-- ۱) وضعیت فعلی
-- ---------------------------------------------------------------------------

SELECT COLUMN_NAME, COLUMN_TYPE, COLUMN_DEFAULT
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME   = 'ad_ratings'
  AND COLUMN_NAME  = 'weight';

-- ---------------------------------------------------------------------------
-- ۲) افزودن ستون، فقط اگر وجود نداشته باشد
-- ---------------------------------------------------------------------------
--
--  MySQL دستور «ADD COLUMN IF NOT EXISTS» ندارد، پس اول شمرده می‌شود
--  و بعد دستور به‌صورت رشته ساخته و اجرا می‌شود. اگر ستون باشد،
--  دستور تبدیل به یک SELECT بی‌ضرر می‌شود.

SET @column_exists := (
    SELECT COUNT(*)
    FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME   = 'ad_ratings'
      AND COLUMN_NAME  = 'weight'
);

SET @sql := IF(
    @column_exists = 0,
    'ALTER TABLE `ad_ratings` ADD COLUMN `weight` DECIMAL(3,2) NOT NULL DEFAULT 1.00 AFTER `rating`',
    'SELECT ''ستون weight از قبل وجود دارد؛ کاری انجام نشد.'' AS message'
);

PREPARE statement FROM @sql;
EXECUTE statement;
DEALLOCATE PREPARE statement;

-- ---------------------------------------------------------------------------
-- ۳) ثبت مهاجرت، تا لاراول دوباره اجرایش نکند
-- ---------------------------------------------------------------------------
--
--  اگر روزی از راه کرون (sazmat:install) هم اجرا شود، نباید دو بار
--  انجام شود. FROM DUAL لازم است چون MySQL اجازه‌ی SELECT ... WHERE
--  بدون FROM نمی‌دهد.

INSERT INTO migrations (migration, batch)
SELECT
    '2026_09_20_000006_add_weight_to_ad_ratings',
    COALESCE((SELECT MAX(batch) FROM (SELECT batch FROM migrations) AS m), 0) + 1
FROM DUAL
WHERE NOT EXISTS (
    SELECT 1 FROM (SELECT migration FROM migrations) AS existing
    WHERE existing.migration = '2026_09_20_000006_add_weight_to_ad_ratings'
);

-- ---------------------------------------------------------------------------
-- ۴) تأیید
-- ---------------------------------------------------------------------------
--
--  باید یک ردیف با نوع decimal(3,2) و پیش‌فرض 1.00 برگردد.

SELECT COLUMN_NAME, COLUMN_TYPE, COLUMN_DEFAULT, IS_NULLABLE
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME   = 'ad_ratings'
  AND COLUMN_NAME  = 'weight';

-- ---------------------------------------------------------------------------
-- ۵) میانگین وزنی آگهی‌ها
-- ---------------------------------------------------------------------------
--
--  همان عددی که سایت نشان خواهد داد. اگر هنوز امتیازی ثبت نشده،
--  خروجی خالی است و این طبیعی است.

SELECT
    a.id,
    a.title,
    COUNT(r.id)                                              AS rating_count,
    ROUND(SUM(r.rating * r.weight) / SUM(r.weight), 1)       AS weighted_average,
    ROUND(AVG(r.rating), 1)                                  AS plain_average
FROM ads a
JOIN ad_ratings r ON r.ad_id = a.id
GROUP BY a.id, a.title
ORDER BY a.id;
