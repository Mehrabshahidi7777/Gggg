-- =============================================================================
--  سازمت | حذف سفارش‌های آزمایشی
-- =============================================================================
--
--  هر ۱۳ سفارش موجود در دیتابیس آزمایشی هستند: مبلغ‌هایی مثل ۱۰۰ و
--  ۱۰۰۰ تومان و شماره تماس‌هایی مثل «G5tg»، «۹۹۹» و «Jjb».
--
--  حذف بر اساس «شماره سفارش» انجام می‌شود، نه شناسه یا شرط کلی.
--  یعنی این فایل دقیقاً همان ۱۳ ردیف شناخته‌شده را هدف می‌گیرد و
--  اگر بعداً سفارش واقعی‌ای ثبت شده باشد، دست نمی‌خورد.
--
--  ------------------------------------------------------------------
--  چرا نیازی به حذف دستیِ order_items نیست
--  ------------------------------------------------------------------
--  یک سفارش در دو جدول پخش شده:
--
--      orders  →  order_items  →  reviews
--
--  کلید خارجی هر دو رابطه ON DELETE CASCADE است، یعنی با حذف ردیف
--  `orders` خودِ دیتابیس آیتم‌ها و نظرهای وابسته را هم پاک می‌کند.
--
--  ⚠️  اگر این فایل را در phpMyAdmin ایمپورت می‌کنید، گزینه‌ی
--      «Enable foreign key checks» باید روشن باشد (حالت پیش‌فرض).
--      اگر خاموش باشد، زنجیره اجرا نمی‌شود و ردیف‌های بی‌صاحب
--      می‌مانند. برای اطمینان، خودِ فایل پایین‌تر بررسی می‌کند.
--
--  در phpMyAdmin روی دیتابیس sazmat_sa ایمپورت کنید.
--  اجرای دوباره‌ی این فایل بی‌خطر است.
-- =============================================================================

SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 1;

-- ---------------------------------------------------------------------------
-- ۱) پیش از حذف: ببینید دقیقاً چه چیزی پاک می‌شود
-- ---------------------------------------------------------------------------
SELECT
    o.`id`,
    o.`order_number`,
    o.`total_amount`,
    o.`phone`,
    o.`status`,
    (SELECT COUNT(*) FROM `order_items` i WHERE i.`order_id` = o.`id`) AS `items_to_delete`
FROM `orders` o
WHERE o.`order_number` IN (
    'SZ-260824005356-F8YNU',
    'SZ-260824014950-3ZIAC',
    'SZ-260905024557-HNFY8',
    'SZ-260905033356-SBWXC',
    'SZ-260906000422-EONKN',
    'SZ-260906002137-MSFB1',
    'SZ-260906002218-RBD2X',
    'SZ-260906214853-MI5WD',
    'SZ-260907161813-Z7VBM',
    'SZ-260911102801-HAHPF',
    'SZ-260914221236-R9G6M',
    'SZ-260914221716-HXTUQ',
    'SZ-260917143933-Q2VGM'
);


-- ---------------------------------------------------------------------------
-- ۲) حذف
-- ---------------------------------------------------------------------------
--
-- ردیف‌های order_items و reviews خودکار (CASCADE) پاک می‌شوند.
--
DELETE FROM `orders`
WHERE `order_number` IN (
    'SZ-260824005356-F8YNU',
    'SZ-260824014950-3ZIAC',
    'SZ-260905024557-HNFY8',
    'SZ-260905033356-SBWXC',
    'SZ-260906000422-EONKN',
    'SZ-260906002137-MSFB1',
    'SZ-260906002218-RBD2X',
    'SZ-260906214853-MI5WD',
    'SZ-260907161813-Z7VBM',
    'SZ-260911102801-HAHPF',
    'SZ-260914221236-R9G6M',
    'SZ-260914221716-HXTUQ',
    'SZ-260917143933-Q2VGM'
);


-- ---------------------------------------------------------------------------
-- ۳) بررسی نهایی
-- ---------------------------------------------------------------------------
--
-- خروجی این دستور باید در هر سه ستون عدد 0 باشد.
--
-- اگر «آیتم‌های بی‌صاحب» صفر نبود، یعنی هنگام ایمپورت گزینه‌ی
-- foreign key checks خاموش بوده. در آن صورت این دستور را جداگانه
-- اجرا کنید تا پاکسازی شود:
--
--     DELETE FROM `order_items`
--     WHERE `order_id` NOT IN (SELECT `id` FROM (SELECT `id` FROM `orders`) AS o);
--
SELECT
    (SELECT COUNT(*) FROM `orders`) AS `سفارش_باقیمانده`,

    (SELECT COUNT(*) FROM `order_items` i
       WHERE NOT EXISTS (SELECT 1 FROM (SELECT `id` FROM `orders`) AS o
                         WHERE o.`id` = i.`order_id`)) AS `آیتم_بی_صاحب`,

    (SELECT COUNT(*) FROM `reviews` r
       WHERE NOT EXISTS (SELECT 1 FROM (SELECT `id` FROM `order_items`) AS i
                         WHERE i.`id` = r.`order_item_id`)) AS `نظر_بی_صاحب`;
