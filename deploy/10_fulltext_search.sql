-- =============================================================================
--  سازمت | ایندکس FULLTEXT برای جست‌وجو
-- =============================================================================
--
--  مسئله چه بود
--  ------------
--  جست‌وجوی سایت این شکلی است:
--
--      WHERE title LIKE '%سیمان%' OR description LIKE '%سیمان%' OR ...
--
--  آن درصدِ ابتدای عبارت یعنی هیچ ایندکسی قابل استفاده نیست. MySQL
--  مجبور است کل جدول `ads` را ردیف به ردیف بخواند - برای هر جست‌وجو،
--  و برای هر ستون. با چند ده آگهی اصلاً حس نمی‌شود؛ با چند هزار آگهی
--  و چند کاربر هم‌زمان، تبدیل می‌شود به کندیِ محسوس.
--
--  این فایل چه می‌کند
--  ------------------
--  یک ایندکس FULLTEXT روی شش ستونی که جست‌وجو می‌شوند می‌سازد. کد
--  سایت خودش تشخیص می‌دهد این ایندکس هست یا نه:
--
--    - اگر باشد  → از MATCH ... AGAINST استفاده می‌کند (سریع، و
--      نتایج بر اساس ارتباط مرتب می‌شوند نه فقط تاریخ)
--    - اگر نباشد → همان LIKE قبلی
--
--  یعنی ایمپورت‌نکردن این فایل چیزی را خراب نمی‌کند، فقط جست‌وجو
--  همان سرعت قبلی را دارد.
--
--  ⚠️ دو نکته که باید بدانید
--  -------------------------
--  ۱. MySQL به‌صورت پیش‌فرض کلمات کمتر از سه نویسه را ایندکس نمی‌کند
--     (innodb_ft_min_token_size). روی هاست اشتراکی این تنظیم قابل
--     تغییر نیست. برای همین کد، عبارت‌های کوتاه مثل «در» را خودش به
--     مسیر LIKE می‌فرستد.
--
--  ۲. FULLTEXT کلمه‌محور است، نه زیررشته‌محور. جست‌وجوی «یمان» (تکه‌ای
--     از وسط «سیمان») با آن نتیجه نمی‌دهد. کد این را هم پوشش داده:
--     اگر مسیر سریع دست خالی برگشت، همان جست‌وجو یک بار دیگر با LIKE
--     اجرا می‌شود. پس نتیجه‌ای که امروز می‌گیرید، بعد از این فایل هم
--     می‌گیرید.
--
--  ⚠️ بعد از ایمپورت، کش را پاک کنید
--  ---------------------------------
--  کد وجود این ایندکس را یک روز کش می‌کند تا هر جست‌وجو یک کوئری
--  اضافه نزند. پس بعد از ایمپورت، محتویات این پوشه را خالی کنید تا
--  همان لحظه اثر کند:
--
--      zzz/bootstrap/cache/
--
--  در phpMyAdmin روی دیتابیس sazmat_sa ایمپورت کنید.
--  اجرای دوباره‌ی این فایل بی‌خطر است.
-- =============================================================================

SET NAMES utf8mb4;

-- ---------------------------------------------------------------------------
-- ۱) وضعیت فعلی
-- ---------------------------------------------------------------------------
--
--  اگر ردیفی برگرداند، ایندکس از قبل ساخته شده و این فایل کاری
--  نمی‌کند.

SELECT
    INDEX_NAME,
    GROUP_CONCAT(COLUMN_NAME ORDER BY SEQ_IN_INDEX) AS columns_in_index,
    INDEX_TYPE
FROM information_schema.STATISTICS
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME   = 'ads'
  AND INDEX_NAME   = 'ads_fulltext'
GROUP BY INDEX_NAME, INDEX_TYPE;

-- ---------------------------------------------------------------------------
-- ۲) ساخت ایندکس، فقط اگر وجود نداشته باشد
-- ---------------------------------------------------------------------------
--
--  MySQL دستور «CREATE INDEX IF NOT EXISTS» ندارد، و ساختن ایندکسِ
--  تکراری خطا می‌دهد. پس اول شمرده می‌شود و بعد دستور به‌صورت رشته
--  ساخته و اجرا می‌شود. اگر ایندکس باشد، دستور تبدیل به یک SELECT
--  بی‌ضرر می‌شود.
--
--  ترتیب ستون‌ها باید دقیقاً با ترتیبی که کد در MATCH می‌نویسد یکی
--  باشد، وگرنه MySQL ایندکس را پیدا نمی‌کند. این ترتیب در
--  App\Models\Ad::FULLTEXT_COLUMNS تعریف شده است.

SET @index_exists := (
    SELECT COUNT(*)
    FROM information_schema.STATISTICS
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME   = 'ads'
      AND INDEX_NAME   = 'ads_fulltext'
);

SET @sql := IF(
    @index_exists = 0,
    'ALTER TABLE `ads` ADD FULLTEXT INDEX `ads_fulltext` (`title`, `description`, `brand`, `model`, `full_name`, `service_title`)',
    'SELECT ''ایندکس ads_fulltext از قبل وجود دارد؛ کاری انجام نشد.'' AS message'
);

PREPARE statement FROM @sql;
EXECUTE statement;
DEALLOCATE PREPARE statement;

-- ---------------------------------------------------------------------------
-- ۳) تأیید
-- ---------------------------------------------------------------------------
--
--  حالا باید دقیقاً یک ردیف با INDEX_TYPE برابر FULLTEXT و شش ستون
--  به همان ترتیب برگردد.

SELECT
    INDEX_NAME,
    GROUP_CONCAT(COLUMN_NAME ORDER BY SEQ_IN_INDEX) AS columns_in_index,
    INDEX_TYPE
FROM information_schema.STATISTICS
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME   = 'ads'
  AND INDEX_NAME   = 'ads_fulltext'
GROUP BY INDEX_NAME, INDEX_TYPE;

-- ---------------------------------------------------------------------------
-- ۴) یک آزمایش سریع
-- ---------------------------------------------------------------------------
--
--  کلمه‌ای را که می‌دانید در یکی از آگهی‌هایتان هست جای «سیمان»
--  بگذارید. اگر ردیف برگشت، ایندکس کار می‌کند.
--
--  (اگر چیزی برنگشت لزوماً خراب نیست: شاید آن کلمه کمتر از سه نویسه
--  باشد یا در هیچ آگهیِ تأییدشده‌ای نباشد.)

SELECT id, title
FROM ads
WHERE MATCH(title, description, brand, model, full_name, service_title)
      AGAINST ('+سیمان*' IN BOOLEAN MODE)
LIMIT 10;
