<?php

namespace App\Http\Controllers\Front;

use App\Http\Controllers\Controller;
use App\Models\Ad;
use Illuminate\Support\Facades\Cache;

/*
|--------------------------------------------------------------------------
| خاموش و روشن کردن موقتِ آگهی
|--------------------------------------------------------------------------
|
| تا امروز تنها راهِ پنهان‌کردن یک آگهی، حذفش بود. کسی که جنسش تمام
| شده یا چند هفته سرش شلوغ است، مجبور بود آگهی را پاک کند و بعد از نو
| بسازد - یعنی عکس‌ها، امتیازها و نظرهایش را برای همیشه از دست بدهد.
|
| ⚠️ این کار با is_suspended فرق دارد.
|
|   is_suspended : سیستم آن را خاموش کرده (اشتراک تمام شده)
|   paused_at    : خودِ صاحب آگهی خاموشش کرده
|
| اگر هر دو روی یک ستون می‌نشستند، اولین اجرای کرون تصمیم کاربر را
| پاک می‌کرد - یا بدتر، آگهیِ تعلیق‌شده به‌خاطر نپرداختن را «فعال»
| می‌کرد.
|
| ⚠️ خاموش‌کردن آگهی، ساعتِ اشتراک را متوقف نمی‌کند. اشتراک برای
| «حق نمایش» است نه «روزهای نمایش»، و متوقف‌کردنش یعنی هر کسی
| می‌تواند اشتراک یک‌ماهه را یک سال کش بدهد. این در پیام صفحه هم به
| کاربر گفته می‌شود.
|
*/
class AdVisibilityController extends Controller
{
    public function pause(Ad $ad)
    {
        $this->authorizeOwner($ad);

        /*
        | از قبل خاموش است: هیچ کاری لازم نیست و تاریخ خاموش‌شدن هم
        | نباید عقب‌وجلو شود. دو بار زدنِ دکمه (یا کلیک دوباره روی
        | صفحه‌ی برگشتی) نباید چیزی را عوض کند.
        */
        if (! $ad->paused_at) {
            $ad->forceFill(['paused_at' => now()])->save();
            $this->forgetSitemap();
        }

        return back()->with('success', 'آگهی موقتاً از سایت برداشته شد. هر وقت خواستی دوباره روشنش کن.');
    }

    public function resume(Ad $ad)
    {
        $this->authorizeOwner($ad);

        if ($ad->paused_at) {
            $ad->forceFill(['paused_at' => null])->save();
            $this->forgetSitemap();
        }

        /*
        | اگر اشتراک تمام شده باشد، آگهی با روشن‌کردن هم به سایت
        | برنمی‌گردد. گفتنش بهتر از این است که کاربر دکمه را بزند،
        | «روشن شد» ببیند، و بعد آگهی‌اش را در سایت پیدا نکند.
        */
        if ($ad->is_suspended) {
            return back()->with(
                'success',
                'آگهی روشن شد، ولی تا تمدید اشتراک در سایت نمایش داده نمی‌شود.'
            );
        }

        return back()->with('success', 'آگهی دوباره روی سایت آمد.');
    }

    /*
    | نقشه‌ی سایت یک ساعت کش می‌شود. بدون پاک‌کردنش، آگهیِ تازه
    | خاموش‌شده تا یک ساعت در فایلی می‌ماند که گوگل از رویش آدرس
    | برمی‌دارد - یعنی گوگل سراغ صفحه‌ای می‌رود که ۴۰۴ می‌دهد، و
    | ۴۰۴های پیاپی به اعتبار دامنه ضربه می‌زند.
    |
    | کلید همان است که SitemapController می‌سازد.
    */
    private function forgetSitemap(): void
    {
        Cache::forget('sitemap.xml');
    }

    private function authorizeOwner(Ad $ad): void
    {
        abort_unless($ad->user_id === auth()->id(), 403);
    }
}
